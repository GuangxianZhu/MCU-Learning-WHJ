    "· 地址线 A：32 根线，CPU 放出要访问的地址，比如 0x2000 0000\n"
    "· 数据线 D：32 根线，真正的数据在这里来回传\n"
    "· 读线 RD、写线 WR：各 1 根，告诉对方这次是“读”还是“写”\n\n"
    "电路图里 32 根并排的线画成一根粗线（Logisim 叫“总线”），旁边写着它现在的值；"
