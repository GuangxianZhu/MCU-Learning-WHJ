    "【一次读】CPU 在地址线放出地址，读/写线设成“读” → 总线看地址的开头，"
    "地址译码器看地址的开头，把对应模块的“选中”线（CS，片选）拉到 1"
    "（0x08… 是 Flash，0x20… 是 SRAM，0x40… 是外设，这叫“地址译码”）→ "
    "那个模块把格子里的数放到数据线上 → CPU 收下。\n\n"
    "【一次写】CPU 在地址线放出地址、在数据线放出数据，读/写线设成“写” → "
    "被选中的模块把数据存进那个格子。\n\n"
    "【取指也是一次读】CPU 每执行一条指令前，都要先按 PC 的地址从 Flash 读出机器码，"
