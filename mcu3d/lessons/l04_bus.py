INTRO = (
    "上一课说 CPU 用地址找到存储器里的格子，那地址和数据是怎么“送过去”的？"
    "答案是芯片里的系统总线。它其实是三组导线：\n\n"
    "· 地址线（紫色）：CPU 放出要访问的地址，比如 0x2000 0000\n"
    "· 数据线（青色）：真正的数据在这里来回传\n"
    "· 读/写控制线：告诉对方这次是“读”（绿色）还是“写”（橙色）\n\n"
    "【一次读】CPU 在地址线放出地址，读/写线设成“读” → 总线看地址的开头，"
    "找到对应的模块（0x08… 是 Flash，0x20… 是 SRAM，0x40… 是外设，这叫“地址译码”）→ "
    "那个模块把格子里的数放到数据线上 → CPU 收下。\n\n"
    "【一次写】CPU 在地址线放出地址、在数据线放出数据，读/写线设成“写” → "
    "被选中的模块把数据存进那个格子。\n\n"
    "【取指也是一次读】CPU 每执行一条指令前，都要先按 PC 的地址从 Flash 读出机器码，"
    "所以总线一直很忙。\n\n"
    "【在模拟器里看】\n"
    "例程 1 是 b = a; a = 0;。按 T 一拍一拍地走，看 3D 画面里紫色的地址包先出发，"
    "青色的数据包再回来（读）或一起过去（写）。下方的“总线”一行写着这一拍地址线、"
    "数据线上的值，以及是读还是写。\n\n"
    "注意第一条 LDR R2, =a：它要从 Flash 后面的文字池读出 a 的地址，"
    "所以这条指令会用总线读两次 Flash（一次取指、一次读常数）。\n\n"
    "【小练习】\n"
    "执行完 b = a; 这一行（前 3 条指令），总线一共被用了几次？其中几次读、几次写？\n"
    "（答案：6 次。3 次取指 + 读文字池 + 读 a，一共 5 次读；写 b 是 1 次写）")


